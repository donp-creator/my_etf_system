def check_all_rules(df, ticker):
    """核心规则调度器：

    系统会把清洗好的数据喂给下面你写的所有奇奇怪怪的规则。
    只要有一个规则触发了“买入”或“卖出”，系统就会立刻把它推送到你手机首屏的卡片里。
    """
    signals = []

    # 获取最新一天的基础数据
    current_price = df["Price"].iloc[-1]

    # ----------------------------------------------------
    # 规则 1：长线对数趋势回调/超买策略（你的核心主线思路）
    # ----------------------------------------------------
    current_z = df["Z_Score"].iloc[-1]
    if current_z < -1.5:
        signals.append(
            {
                "action": "买入",
                "strategy": "长线回归回调",
                "reason": f"价格严重跌破长期对数趋势线（当前Z-Score: {current_z:.2f}），处于历史极端估值低位，大涨概率高。",
            }
        )
    elif current_z > 1.5:
        signals.append(
            {
                "action": "卖出",
                "strategy": "长线回归超买",
                "reason": f"价格严重向上偏离长期对数趋势线（当前Z-Score: {current_z:.2f}），过热，建议暂停定投或适当止盈。",
            }
        )

    # ----------------------------------------------------
    # 规则 2：中期均值回归策略（基于短期价格偏离度）
    # 逻辑：价格在10-20年大趋势向上时，中期经常会有剧烈踩坑。
    # 这是一个高胜率的左侧捞底指标：计算价格偏离50日移动平均线的比例。
    # ----------------------------------------------------
    ma50 = df["MA_50"].iloc[-1]
    ma_deviation = (current_price - ma50) / ma50

    if ma_deviation < -0.10:  # 价格比50日线低10%以上
        signals.append(
            {
                "action": "买入",
                "strategy": "中期均值超跌",
                "reason": f"当前价格距离50日均线偏离度达 {ma_deviation*100:.1f}%，属于中期严重超跌，均值回归反弹概率大。",
            }
        )

    # ----------------------------------------------------
    # 规则 3：时序横盘突破策略（你提到的“过去X天有过Y特征”）
    # 逻辑：观察过去10天（X）的滚动振幅是否被压缩到了极低水平（Y）。
    # 如果振幅连续极小（横盘），说明多空双方达到临界点，一旦价格重新站上250日牛熊分界线，往往迎来大爆发。
    # ----------------------------------------------------
    last_10_days_amplitude = df["Amplitude_10"].iloc[-1]
    ma250 = df["MA_250"].iloc[-1]

    # 如果过去10天总振幅小于 3% (极度横盘)，且价格维持在250日长线均线上方支撑位
    if last_10_days_amplitude < 0.03 and current_price > ma250:
        signals.append(
            {
                "action": "买入",
                "strategy": "牛市地量横盘",
                "reason": f"过去10天振幅仅为 {last_10_days_amplitude*100:.1f}%，处于极度横盘状态，且在250日牛线上方企稳，随时可能向上大变盘。",
            }
        )

    # ----------------------------------------------------
    # 终审判决逻辑：如果没有触发买卖，默认返回观望
    # ----------------------------------------------------
    if not signals:
        return "观望", "处于正常波动区间，无明显择时信号。"

    # 优先返回列表中第一个被触发的明确信号（你可以调整这里的优先级）
    first_trigger = signals[0]
    return (
        first_trigger["action"],
        f"【{first_trigger['strategy']}】{first_trigger['reason']}",
    )
