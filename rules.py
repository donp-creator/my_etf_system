def check_all_rules(df, ticker):
    """
    量化策略调度中心（策略层）
    由规则本身决定动作、原因以及最终的优先级得分 (Priority Score)。
    未来加入任何新规则（如仓位控制、宏观共振），直接在这里更新 score 即可，前端app.py完全不需要动！
    """
    # 提取最新一行的核心特征特征值
    current_price = float(df["Price"].iloc[-1])
    z_score = float(df["Z_Score"].iloc[-1])
    amp_10 = float(df["Amplitude_10"].iloc[-1])
    
    ma_50 = float(df["MA_50"].iloc[-1])
    ma_bias = (current_price - ma_50) / ma_50 if ma_50 != 0 else 0
    
    # 默认状态
    action = "观望"
    reason = "当前所有监控指标均处于正常长线对数回归轨道内，建议继续耐心持仓守候。"
    priority_score = 0.0
    
    # ----------------------------------------------------
    # 【规则库第一案】：长线对数回归下轨回调买入
    # ----------------------------------------------------
    if z_score < -1.5:
        action = "买入"
        reason = f"【长线回归回调】当前标的价格已严重跌破长线对数趋势轨道（当前Z-Score为: {z_score:.2f}），处于历史极端估值低位，大涨概率高。"
        # 基础得分：Z-Score越负，得分越高
        priority_score = abs(z_score) * 2.0

    # ----------------------------------------------------
    # 【规则库第二案】：中期均值超跌严重（短线回调择时）
    # ----------------------------------------------------
    elif ma_bias < -0.10:
        action = "买入"
        reason = f"【中期均值超跌】当前价格距离50日均线偏离度达 {ma_bias*100:.1f}%，属于中期严重超跌，均值回归反弹概率大。"
        priority_score = abs(ma_bias) * 15.0

    # ----------------------------------------------------
    # 【规则库第三案】：牛市地量横盘变盘择时
    # ----------------------------------------------------
    elif amp_10 < 0.03 and z_score > 0:
        action = "买入"
        reason = f"【牛市地量横盘】过去10天振幅仅为 {amp_10*100:.1f}%，处于极度横盘状态，且在250日牛线上方企稳，随时可能向上大变盘。"
        priority_score = 5.0  # 给予一个固定的变盘高分级

    # ----------------------------------------------------
    # 【规则库第四案】：长线回归超买（逢高分批锁利）
    # ----------------------------------------------------
    elif z_score > 1.8:
        action = "卖出"
        reason = f"【长线回归超买】价格严重向上偏离长期对数趋势线（当前Z-Score为: {z_score:.2f}），市场情绪过热，建议暂停定投或适当止盈。"
        priority_score = z_score * 2.0

    # ----------------------------------------------------
    # 💡【未来扩展区】：在这里你可以叠加你的千奇百怪规则（如：仓位管理、VIX恐慌指标）
    # ----------------------------------------------------
    # 示例伪代码（未来只需在这里更新 score 和仓位提示即可）：
    # if trigger_your_new_rule:
    #     action = "买入"
    #     position_size = 0.20  # 比如未来计算出20%仓位
    #     reason += f" | 【策略提示】推荐分配仓位: {position_size*100}%"
    #     priority_score += 10.0  # 叠加新规则的分数奖励
        
    return action, reason, float(priority_score)
